"""Generate the comparison report from computed results and a labeled paper table."""
import json
from pathlib import Path

from .experiments import PAPER_NAMES


def write_reproduction(output_dir="outputs"):
    output_dir = Path(output_dir).resolve()
    docs = output_dir.parent / "docs"
    paper = json.loads((docs / "paper_table1.json").read_text(encoding="utf-8"))
    results = json.loads((output_dir / "results/results.json").read_text(encoding="utf-8"))
    aggregate = results["experiment_1"]["aggregate"]
    cnp, greedy = aggregate["Contract-Net"], aggregate["Greedy-Centralized"]
    ci = results["experiment_1"]["bootstrap_cnp_vs_gc"]["makespan"]
    saving = 100 * (1 - cnp["messages"]["mean"] / greedy["messages"]["mean"])
    difference_pct = 100 * (cnp["makespan"]["mean"] / greedy["makespan"]["mean"] - 1)
    lines = ["# Reproduction against Table 1", "",
        "Generated by `python scripts/run_all.py` (or `python scripts/write_reproduction.py`) from "
        "`outputs/results/results.json`. Reference values are transcribed, explicitly labeled data in "
        "`docs/paper_table1.json`; none are used to generate scenarios or select parameters.", "",
        "## Main finding", "",
        "The recovered June implementation and the later paper are numerically inconsistent. "
        "The four recovered mechanisms reproduce all 30 saved trials' original metrics within numerical tolerance "
        "(`tests/test_recovered_base.py`), including loads, token proxy, and latency. "
        "The discrepancy with Table 1 therefore predates this extension; changing parameters to erase it would "
        "break the recovered implementation. SSI and CBBA are reconstructions, not recovered implementations.", "",
        f"CNP makespan is {cnp['makespan']['mean']:.2f} versus greedy {greedy['makespan']['mean']:.2f} "
        f"({difference_pct:+.2f}%). Message saving is {saving:.2f}%. "
        f"The paired CNP-minus-greedy makespan difference is {ci['mean_difference']:.2f}, "
        f"with bootstrap 95% CI [{ci['ci_low']:.2f}, {ci['ci_high']:.2f}]. "
        "This interval does not establish equivalence or a 1% noninferiority bound.", "",
        "## Table 1, side by side", "",
        "Each entry is mean ± population standard deviation, preserving the recovered code's `ddof=0`. "
        "Experiment 1 uses 12 agents, expected 200 tasks, H=500, k=5, a 25-unit batch window, and seeds 0–29. "
        "Wait includes travel, as in the recovered code. The token row uses the recovered June prices.", ""]
    titles = ["Makespan", "Mean service wait", "95th-percentile service wait", "Jain fairness",
              "Messages", "Throughput", "Token proxy (June model)"]
    for index, (metric, title) in enumerate(zip(paper["metric_order"], titles)):
        precision = 3 if metric in ("fairness", "throughput") else (0 if metric == "proxy_tokens" else 1)
        lines += [f"### {title}", "", "| Mechanism | Paper Table 1 | Regenerated |", "|---|---:|---:|"]
        for name in PAPER_NAMES.values():
            mean, std = paper[name][index]
            row = aggregate[name][metric]
            lines.append(f"| {name} | {mean:,.{precision}f} ± {std:,.{precision}f} | "
                         f"{row['mean']:,.{precision}f} ± {row['std']:,.{precision}f} |")
        lines.append("")
    lines += ["## Diagnosis, without parameter fitting", "",
        "- The expected qualitative message ordering holds: CBBA has the most messages; CNP saves exactly "
        "13/24 = 54.1667% versus greedy when n=12 and k=5. This saving is an accounting identity, not a statistical discovery.",
        "- Nearest-agent remains clearly worse than CNP. CNP and greedy are close, but their mean makespans differ "
        "by more than 1% in this recovered configuration. The later paper's much shorter waits and smaller makespans "
        "are not reproduced. It omits the speed distribution; the recovered source fixes it at U(0.8,1.3). "
        "There is insufficient evidence to attribute the later values to a particular changed parameter or code defect.",
        "- Both wait definitions are saved. Changing service wait to queue-only wait does not justify silently replacing "
        "the original definition. All tasks drain after the arrival horizon; throughput is T/makespan.",
        "- The paper's token assumptions differ from June's. `paper_tokens` applies the later prices to the same "
        "observed ledger, while `proxy_tokens` and `estimated_token_cost` preserve June's model. This isolates "
        "pricing changes from allocation changes.",
        "- This synchronous append-only CBBA is close to SSI in allocation quality. Its message magnitude is close "
        "to Table 1, but neither matching magnitude nor the algorithm's name recovers the lost variant. "
        "Claiming CBBA is inherently worse in quality is not supported by this implementation.", "",
        "### Same ledger repriced with the paper's token constants", "",
        "| Mechanism | June token model | Later-paper token model |", "|---|---:|---:|"]
    for name in PAPER_NAMES.values():
        lines.append(f"| {name} | {aggregate[name]['proxy_tokens']['mean']:,.0f} | {aggregate[name]['paper_tokens']['mean']:,.0f} |")
    lines += ["", "## Further experiment checks", ""]
    n32 = results["experiment_2"]["by_team_size"]["32"]
    lines.append(f"At n=32, CNP makespan is {n32['Contract-Net']['makespan']['mean']:.2f} versus "
                 f"{n32['Greedy-Centralized']['makespan']['mean']:.2f} for greedy, and its message saving is "
                 f"{100*(1-n32['Contract-Net']['messages']['mean']/n32['Greedy-Centralized']['messages']['mean']):.2f}%.")
    lines += ["", "| Mechanism | Makespan / exact offline optimum (mean ± std) |", "|---|---:|"]
    for name, stat in results["experiment_4"]["ratio_to_optimal"].items():
        lines.append(f"| {name} | {stat['mean']:.3f} ± {stat['std']:.3f} |")
    robust = results["experiment_5"]["results"]
    single = robust["single_round"]["0.5"]
    rebid = robust["rebid"]["0.5"]
    lines += ["", "The later paper's re-bidding improvement is also not reproduced: at noise σ=0.5, "
        f"single-round makespan is {single['makespan']['mean']:.2f} and one-re-bid makespan is "
        f"{rebid['makespan']['mean']:.2f}, with {rebid['rebid_rounds']['mean']:.2f} extra rounds per trial. "
        "The recovered policy excludes an underquoted winner, which can exclude a truly good agent; "
        "re-bidding is not guaranteed to improve allocation. The paper experiment's explicit 1.25 threshold "
        "is used; June's compatibility default remains 1.35. No threshold or randomness was tuned."]
    lines += ["", "At four agents and k=5 capped at n, clean CNP and greedy have identical assignments and gaps. "
        "The paper's unequal gaps cannot follow from that setup. The exact solver permits task reordering and "
        "immediate release-time decisions; batch methods wait until window close, so their gap includes that policy restriction.", "",
        f"For CNP in Experiment 1, mean last arrival is {cnp['last_arrival']['mean']:.2f}, "
        f"mean drain time is {cnp['drain_time']['mean']:.2f}, mean queue-only wait is {cnp['mean_queue_wait']['mean']:.2f}, "
        f"and mean response time is {cnp['mean_response']['mean']:.2f}. These diagnostics expose arrival-horizon effects.", "",
        "## Reproduction commands and evidence", "",
        "```powershell", "python -m pip install -r requirements.txt", "python -m pytest -q",
        "python scripts/run_all.py", "python scripts/make_figures.py", "```", "",
        "Raw per-trial CSVs, five summaries, the combined later-layout JSON, and seed-0 message/schedule audits "
        "are under `outputs/`. The seven figures have 12 cm physical width, 11 pt fonts, markers/hatches, "
        "300 dpi PNGs and vector PDFs. `outputs/figures/manifest.json` maps paper figure numbers to filenames. "
        "The original saved artifacts remain under `outputs/recovered_original/` and are never used as generated results.", "",
        "No live LLM experiment was implemented or run. No API request was made. See `docs/model_notes.md` "
        "for recovered design details and the environment-key presence check.", ""]
    path = docs / "reproduction.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path

from pathlib import Path

import numpy as np

from .domain import Agent, Task, bid, execution_time, travel_time
from .scenario import Scenario, ScenarioConfig
from .simulation import simulate
from .v2 import NAMES


def running_scenario():
    return Scenario(ScenarioConfig(n_agents=3, expected_tasks=1, n_skills=1),
                    [Agent(0, np.array([0., 0.]), np.array([.5]), 2, busy_until=10),
                     Agent(1, np.array([6., 0.]), np.array([1.]), 2, busy_until=4),
                     Agent(2, np.array([6., 8.]), np.array([.25]), 1, busy_until=4)],
                    [Task(0, 0, 6., np.array([6., 8.]), 4.)], 0)


def write_example(path='docs/running_example.md'):
    scenario = running_scenario()
    task = scenario.tasks[0]
    lines = ['# Verified running example', '', 'Generated by `mas_sim.example.write_example`; tested against the real simulator.', '',
             'Three registered agents; one managed task arrives at time 4, at (6, 8), workload 6, required skill 0, no deadline. '
             'Pre-existing queue endpoints/finish times are known at registration. Default soft proficiency (theta=0); CNP k=2, fresh capability shortlist.', '',
             'Bid = max(0, committed finish - now) + Euclidean distance / speed + workload / max(skill, 0.05). '
             'The capability shortlist uses only the last two terms, never private backlog.', '',
             '| Agent | Position | Speed | Skill | Finish | Backlog | Travel | Execution | Registry score | Bid |',
             '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for agent in scenario.agents:
        travel, execution = travel_time(agent, task), execution_time(agent, task)
        lines.append(f'| {agent.id} | {agent.position.tolist()} | {agent.speed} | {agent.skills[0]} | {agent.busy_until} | '
                     f'{max(0,agent.busy_until-4):g} | {travel:g} | {execution:g} | {travel+execution:g} | {bid(agent, task, 4):g} |')
    lines += ['', 'Agent 0: distance sqrt(6²+8²)=10, travel=10/2=5; execution=6/0.5=12; backlog=10-4=6; bid=23. '
              'Agent 1: distance=8, travel=8/2=4; execution=6/1=6; backlog=0; bid=10. '
              'Agent 2: distance=0, travel=0; execution=6/0.25=24; backlog=0; bid=24.', '',
              'Capability order is 1, 0, 2. Nearest order is 2, 1, 0. The k=2 capability bidders quote 10 and 23, so agent 1 wins. '
              'Its dispatch is max(4,4)=4, service starts at 4+4=8, completes at 8+6=14: wait=4, response=10. '
              'The registry receives position (6,8) and committed finish 14.', '',
              '| Mechanism | Winner | Decision | Service start | Completion | Messages including registration |',
              '|---|---:|---:|---:|---:|---:|']
    results = {name: simulate(scenario, name, k=2) for name in NAMES}
    for name, result in results.items():
        a = result.assignments[0]
        lines.append(f'| {NAMES[name]} | {a.agent_id} | {a.decision:g} | {a.service_start:g} | {a.finish:g} | {len(result.ledger.messages)} |')
    lines += ['', 'SSI/CBBA wait until the first 25-unit batch closes. They choose agent 1 at time 25, start service at 29, and finish at 35. '
              'Their response=31 includes batching. CBBA needs three consensus rounds: initial competing claims, losing-bundle release, then unchanged certification (3×3×2=18 directed messages). '
              'All methods publish three initial cards. SSI uses live vector bids and CBBA live consensus; neither reads the registry after initialization or sends unused status updates.', '']
    for name, result in results.items():
        lines += [f'## {NAMES[name]}', '', '| Type | Sender | Receiver | Task ids | Round |', '|---|---|---|---|---:|']
        for m in result.ledger.messages:
            lines.append(f'| {m.type} | {m.sender} | {m.receiver} | {list(m.task_ids)} | {m.round_id} |')
        lines.append('')
    Path(path).write_text('\n'.join(lines)+'\n', encoding='utf-8')

